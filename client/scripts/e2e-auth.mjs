// Live check of the server-side auth behaviour the sign-in / reset screens rely on.
// It sends NO email: the recovery link is generated through the admin API, and the
// one reset request goes to an address that has no account. It creates one
// throwaway user and deletes it at the end.
//
//   SUPABASE_URL=... SUPABASE_ANON_KEY=... SUPABASE_SERVICE_KEY=... node scripts/e2e-auth.mjs
import { createClient } from '@supabase/supabase-js';

const { SUPABASE_URL, SUPABASE_ANON_KEY, SUPABASE_SERVICE_KEY } = process.env;
if (!SUPABASE_URL || !SUPABASE_ANON_KEY || !SUPABASE_SERVICE_KEY) {
  console.error('Set SUPABASE_URL, SUPABASE_ANON_KEY and SUPABASE_SERVICE_KEY.');
  process.exit(2);
}
const mk = (key) => createClient(SUPABASE_URL, key, { auth: { persistSession: false, autoRefreshToken: false } });
const admin = mk(SUPABASE_SERVICE_KEY);

let pass = 0;
const failures = [];
const check = (name, cond, detail = '') => {
  if (cond) { pass += 1; console.log(`  ok   ${name}`); } else { failures.push(name); console.log(`  FAIL ${name}${detail ? ` — ${detail}` : ''}`); }
};

const tag = `auth-${Date.now()}`;
const email = `${tag}@example.com`;
const P1 = `${crypto.randomUUID()}-first`;
const P2 = `${crypto.randomUUID()}-second`;
let userId = null;

async function run() {
  console.log('Setup: an unconfirmed account (as after sign-up, before clicking the email link)');
  const created = await admin.auth.admin.createUser({ email, password: P1, email_confirm: false, user_metadata: { display_name: 'Auth Tester' } });
  if (created.error) throw new Error(created.error.message);
  userId = created.data.user.id;

  console.log('\nSign-in errors');
  const unconfirmed = await mk(SUPABASE_ANON_KEY).auth.signInWithPassword({ email, password: P1 });
  check('an unconfirmed account cannot sign in', !!unconfirmed.error);
  check('...and the error code is email_not_confirmed (the screen offers "resend")', unconfirmed.error?.code === 'email_not_confirmed', unconfirmed.error?.code);

  const wrongPw = await mk(SUPABASE_ANON_KEY).auth.signInWithPassword({ email, password: 'definitely-wrong' });
  const noUser = await mk(SUPABASE_ANON_KEY).auth.signInWithPassword({ email: `nobody-${tag}@example.com`, password: 'definitely-wrong' });
  check('an unknown email is refused', !!noUser.error);
  check('a wrong password on a real (unconfirmed) account and an unknown email give the identical code and message — no account enumeration',
    wrongPw.error?.code === 'invalid_credentials' && noUser.error?.code === 'invalid_credentials' && wrongPw.error?.message === noUser.error?.message,
    `${wrongPw.error?.code}:${wrongPw.error?.message} vs ${noUser.error?.code}:${noUser.error?.message}`);

  console.log('\nSign-up validation (rejected before any account or email is created)');
  const weak = await mk(SUPABASE_ANON_KEY).auth.signUp({ email: `weak-${tag}@example.com`, password: 'abc' });
  check('a very short password is rejected by the server', !!weak.error, weak.error?.message);
  check('...with the weak_password code', weak.error?.code === 'weak_password', weak.error?.code);
  const leftover = await admin.auth.admin.listUsers({ page: 1, perPage: 200 });
  check('...and no account was created for it', !(leftover.data?.users || []).some((u) => u.email === `weak-${tag}@example.com`));

  console.log('\nConfirmed account: profile and sign-in');
  await admin.auth.admin.updateUserById(userId, { email_confirm: true });
  const profile = await admin.from('profiles').select('display_name, peer_code').eq('id', userId).single();
  check('the sign-up name became the profile display name', profile.data?.display_name === 'Auth Tester', JSON.stringify(profile));
  check('the account has a peer code', /^PEER-/.test(profile.data?.peer_code || ''));

  const sessionA = mk(SUPABASE_ANON_KEY);
  const sessionB = mk(SUPABASE_ANON_KEY);
  const a = await sessionA.auth.signInWithPassword({ email, password: P1 });
  const b = await sessionB.auth.signInWithPassword({ email, password: P1 });
  check('a confirmed account signs in (two separate sessions)', !a.error && !b.error, a.error?.message || b.error?.message);

  console.log('\nPassword reset (link generated by admin — no email sent)');
  const noUserReset = await mk(SUPABASE_ANON_KEY).auth.resetPasswordForEmail(`nobody-${tag}@example.com`);
  check('a reset request for an unknown address succeeds the same way (no account enumeration)', !noUserReset.error, noUserReset.error?.message);

  const link = await admin.auth.admin.generateLink({ type: 'recovery', email });
  const tokenHash = link.data?.properties?.hashed_token;
  check('a recovery link can be generated', !link.error && !!tokenHash, link.error?.message);

  const recovery = mk(SUPABASE_ANON_KEY);
  const verified = await recovery.auth.verifyOtp({ type: 'recovery', token_hash: tokenHash });
  check('opening the recovery link signs the user in', !verified.error && !!verified.data?.session, verified.error?.message);

  const reuse = await mk(SUPABASE_ANON_KEY).auth.verifyOtp({ type: 'recovery', token_hash: tokenHash });
  check('a recovery link cannot be used twice', !!reuse.error);

  const same = await recovery.auth.updateUser({ password: P1 });
  check('the new password cannot equal the old one', same.error?.code === 'same_password', `${same.error?.code}: ${same.error?.message}`);

  const upd = await recovery.auth.updateUser({ password: P2 });
  check('the user can set a new password', !upd.error, upd.error?.message);
  await recovery.auth.signOut({ scope: 'others' });

  const stillA = await sessionA.auth.getUser();
  const stillB = await sessionB.auth.getUser();
  check('other sessions are ended after a reset (session A)', !!stillA.error || !stillA.data?.user);
  check('other sessions are ended after a reset (session B)', !!stillB.error || !stillB.data?.user);
  const current = await recovery.auth.getUser();
  check('the session that reset the password stays signed in', !current.error && current.data?.user?.id === userId, current.error?.message);

  const oldPw = await mk(SUPABASE_ANON_KEY).auth.signInWithPassword({ email, password: P1 });
  const newPw = await mk(SUPABASE_ANON_KEY).auth.signInWithPassword({ email, password: P2 });
  check('the old password no longer works', !!oldPw.error);
  check('the new password works', !newPw.error, newPw.error?.message);
}

try {
  await run();
} catch (e) {
  failures.push(`aborted: ${e.message}`);
  console.error(`\nABORTED: ${e.message}`);
} finally {
  console.log('\nCleanup');
  if (userId) {
    const { error } = await admin.auth.admin.deleteUser(userId);
    console.log(`  ${error ? `FAILED to delete test user: ${error.message}` : 'deleted the test user'}`);
  }
  const { data } = await admin.auth.admin.listUsers({ page: 1, perPage: 200 });
  const left = (data?.users || []).filter((u) => (u.email || '').includes(tag));
  check('no test users remain', left.length === 0, `${left.length} left`);
}

console.log(`\n${pass} passed, ${failures.length} failed`);
if (failures.length) { console.log('Failures:\n - ' + failures.join('\n - ')); process.exit(1); }
